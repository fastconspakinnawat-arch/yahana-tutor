def spell_gen(rng, mc, i):
    order = spell_gen.order
    k = order[i % len(order)]
    right, wrong = SPELL[k]
    others = [SPELL[j] for j in rng.sample(range(len(SPELL)), 8) if j != k][:3]
    if i % 3 == 2:
        return mc('ข้อใด<b>สะกดผิด</b>', wrong, [o[0] for o in others],
                  ol(f'“{wrong}” สะกดผิด ที่ถูกคือ “{right}”', 'ตัวเลือกอื่นสะกดถูกต้องตามพจนานุกรมฉบับราชบัณฑิตยสถาน'),
                  h='อ่านทีละคำ แล้วนึกถึงคำที่คนมักเขียนผิด')
    return mc('ข้อใด<b>สะกดถูกต้อง</b>', right, [o[1] for o in others],
              ol(f'“{right}” สะกดถูกต้อง (มักเขียนผิดเป็น “{wrong}”)',
                 'ตัวเลือกอื่นที่ถูก: ' + ', '.join(f'{o[1]} → {o[0]}' for o in others)),
              h='ระวังคำที่ออกเสียงเหมือนกันแต่สะกดต่างกัน')


def spell_build(rng, n=30):
    spell_gen.order = rng.sample(range(len(SPELL)), len(SPELL))
    return custom_topic(spell_gen)(rng, n)


