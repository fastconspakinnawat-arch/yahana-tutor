def dec_frac(rng, mc):
    d = rng.choice([2, 4, 5, 8, 10, 20, 25]); n = R(rng, 1, d - 1)
    v = Fr(n, d)
    if v.denominator != d: return dec_frac(rng, mc)
    return mc(f'{fr(n,d)} เขียนเป็นทศนิยมได้ตรงกับข้อใด', num(v), [num(v + Fr(1, 10)), num(v / 10), num(Fr(d, 100) if Fr(d,100) != v else v * 2), num(Fr(n, 10) if Fr(n,10) != v else v + Fr(1,100)), num(v * 10)],
              ol(f'{fr(n,d)} = {n} ÷ {d}', f'= {num(v)}'))

