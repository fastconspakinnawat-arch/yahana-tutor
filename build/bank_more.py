    a, b, c, A = rng.choice(HERON); s = Fr(a + b + c, 2)
    if rng.random() < .5:
        return NUM(f'สามเหลี่ยมมีด้านยาว {a}, {b}, {c} หน่วย มีพื้นที่กี่ตารางหน่วย', A, ol(f's = {fr(a+b+c,2) if (a+b+c)%2 else (a+b+c)//2}', f'พื้นที่ = √[s(s − a)(s − b)(s − c)] = {A}'), h='สูตรเฮรอน')
