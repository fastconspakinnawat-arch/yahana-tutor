def shop(rng, mc):
    p1, n1, p2, n2 = R(rng, 5, 60), R(rng, 2, 9), R(rng, 5, 60), R(rng, 2, 9)
    pay = (p1 * n1 + p2 * n2 + 99) // 100 * 100
    return NUM(f'ซื้อสมุดเล่มละ {p1} บาท {n1} เล่ม และปากกาด้ามละ {p2} บาท {n2} ด้าม จ่ายแบงก์ {pay} บาท ได้เงินทอนกี่บาท', pay - p1 * n1 - p2 * n2,
               ol(f'สมุด {p1} × {n1} = {p1*n1}, ปากกา {p2} × {n2} = {p2*n2}', f'รวม {p1*n1+p2*n2} บาท', f'เงินทอน {pay} − {p1*n1+p2*n2} = {pay-p1*n1-p2*n2} บาท'), u='บาท')

