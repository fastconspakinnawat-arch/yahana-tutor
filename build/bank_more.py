def digit_sum_mod(rng, mc):
    n = R(rng, 10**6, 10**9)
    return NUM(f'เศษจากการหาร {n} ด้วย 9 เท่ากับเท่าใด', n % 9, ol('เศษจากการหารด้วย 9 = เศษของผลบวกเลขโดด', f'ผลบวกเลขโดด = {sum(map(int, str(n)))} → เศษ {n % 9}'), h='ใช้ผลบวกเลขโดด')

def lcm_word(rng, mc):
    a, b, c = rng.sample([3, 4, 5, 6, 7, 8, 9], 3); r = R(rng, 1, min(a, b, c) - 1)
    L = math.lcm(a, b, c)
    return NUM(f'จำนวนนับที่น้อยที่สุดที่มากกว่า {r} ซึ่งหารด้วย {a}, {b} และ {c} แล้วเหลือเศษ {r} ทุกครั้ง คือเท่าใด', L + r, ol(f'จำนวนนั้น − {r} ต้องหารด้วย {a}, {b}, {c} ลงตัว', f'ค.ร.น. = {L}', f'คำตอบ = {L} + {r} = {L+r}'))

