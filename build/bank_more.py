def line_val(rng, mc):
    m, c, x = R(rng, -5, 6), R(rng, -10, 10), R(rng, -5, 8)
    k = rng.randrange(3)
    if k == 0: return NUM(f'เส้นตรง y = {m}x{sgn(c)} ผ่านจุด ({x}, k) ค่า k เท่ากับเท่าใด'.replace('= 1x', '= x').replace('= -1x', '= −x'), m * x + c, ol(f'k = {m}({x}){sgn(c)} = {m*x+c}'))
    if k == 1: return NUM(f'เส้นตรง y = {m}x{sgn(c)} ตัดแกน y ที่จุด (0, k) ค่า k เท่ากับเท่าใด'.replace('= 1x', '= x'), c, ol(f'แทน x = 0 ได้ y = {c}'))
    a, b = R(rng, 1, 6), R(rng, 1, 6); cc = a * b * R(rng, 1, 3)
    return MCN(mc, f'ความชันของเส้นตรง {a}x + {b}y = {cc} เท่ากับเท่าใด', Fr(-a, b), ol(f'เขียนใหม่: y = −{fr(a,b)}x + {fr(cc,b)}', f'ความชัน = −{fr(a,b)}' if b > 1 else f'ความชัน = −{a}'), extra=[Fr(a, b), Fr(-b, a), Fr(b, a)])

