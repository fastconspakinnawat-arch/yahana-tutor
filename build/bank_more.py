    if rng.random() < .5:
        return NUM(f'{num(a)} × {b} มีค่าเท่าใด', a * b, ol(f'{a.numerator} × {b} = {a.numerator*b}', f'มีทศนิยม 1 ตำแหน่ง → {num(a*b)}'))
