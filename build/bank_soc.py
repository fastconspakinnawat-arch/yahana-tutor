def trade_bal(rng, mc):
    ex, im = R(rng, 50, 300) * 10, R(rng, 50, 300) * 10
    if ex == im: im += 40
    d = ex - im
    return NUM(f'ประเทศหนึ่งส่งออกสินค้ามูลค่า {num(ex)} ล้านบาท และนำเข้า {num(im)} ล้านบาท ดุลการค้าเท่ากับกี่ล้านบาท (ขาดดุลตอบเป็นลบ)',
               d, ol('ดุลการค้า = มูลค่าส่งออก − มูลค่านำเข้า', f'= {num(ex)} − {num(im)} = {num(d)} ล้านบาท',
                     'ได้ดุล' if d > 0 else 'ขาดดุล'), u='ล้านบาท')


def interest(rng, mc):
    p, r, t = R(rng, 1, 20) * 1000, rng.choice([1, 2, 3, 4, 5]), R(rng, 1, 5)
    i = p * r * t // 100
    return NUM(f'ฝากเงิน {num(p)} บาท ได้ดอกเบี้ยแบบไม่ทบต้นร้อยละ {r} ต่อปี เป็นเวลา {t} ปี จะได้ดอกเบี้ยรวมกี่บาท', i,
               ol('ดอกเบี้ย = เงินต้น × อัตรา × เวลา', f'= {num(p)} × {r}/100 × {t} = {num(i)} บาท'), u='บาท')


