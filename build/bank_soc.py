def time_zone(rng, mc):
    a = rng.choice([0, 15, 30, 45, 60, 75, 90, 105, 120, 135, 150])
    b = rng.choice([x for x in [0, 15, 30, 45, 60, 75, 90, 105, 120, 135, 150] if x != a])
    h = abs(a - b) // 15
    return NUM(f'เมือง ก อยู่ลองจิจูด {a}° ตะวันออก เมือง ข อยู่ลองจิจูด {b}° ตะวันออก เวลาของสองเมืองต่างกันกี่ชั่วโมง', h,
               ol('โลกหมุน 360° ใน 24 ชั่วโมง → ลองจิจูดต่างกัน 15° เวลาต่างกัน 1 ชั่วโมง', f'ต่างกัน {abs(a-b)}° → {abs(a-b)} ÷ 15 = {h} ชั่วโมง'), u='ชั่วโมง')


def map_scale(rng, mc):
    s = rng.choice([10000, 20000, 25000, 50000, 100000, 250000])
    cm = R(rng, 2, 12)
    km = Fr(s * cm, 100000)
    return NUM(f'แผนที่มาตราส่วน 1 : {num(s)} ระยะบนแผนที่ {cm} เซนติเมตร คิดเป็นระยะจริงกี่กิโลเมตร', km,
               ol(f'ระยะจริง = {cm} × {num(s)} = {num(cm*s)} cm', f'1 km = 100,000 cm → {num(cm*s)} ÷ 100,000 = {num(km)} km'), u='km')


