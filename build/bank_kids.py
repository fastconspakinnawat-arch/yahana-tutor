def k_count(rng, mc):
    e, name, cl = rng.choice(THINGS); n = R(rng, 1, 10)
    return NUM(f'นับดูซิ มี{name}กี่{cl}{pic(e, n)}', n, ol(f'ชี้นับทีละ{cl}: ' + ', '.join(str(i) for i in range(1, n + 1)), f'มี{name} {n} {cl}'), u=cl, h='ชี้นิ้วนับทีละอัน')


def k_more(rng, mc):
    (e1, n1, c1), (e2, n2, c2) = rng.sample(FRUIT, 2) if rng.random() < .5 else rng.sample(ANIMAL, 2)
    a, b = R(rng, 1, 9), R(rng, 1, 9)
    if a == b: b = a + 1
    if rng.random() < .5:
        big = n1 if a > b else n2
        return mc(f'อะไรมีมากกว่ากัน{pic(e1, a)}{pic(e2, b)}', big, [n2 if big == n1 else n1, 'เท่ากัน', 'ไม่มีทั้งสองอย่าง'],
                  ol(f'{n1} มี {a}, {n2} มี {b}', f'{max(a,b)} มากกว่า {min(a,b)} → {big} มีมากกว่า'))
    return NUM(f'{n1}มากกว่าหรือน้อยกว่า{n2}อยู่กี่{c1}{pic(e1, a)}{pic(e2, b)}', abs(a - b),
               ol(f'{n1} มี {a}, {n2} มี {b}', f'ต่างกัน {max(a,b)} − {min(a,b)} = {abs(a-b)}'), u=c1, h='จับคู่ทีละอัน แล้วนับที่เหลือ')


