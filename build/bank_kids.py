TH_DIGIT = '๐๑๒๓๔๕๖๗๘๙'
WORDS = ['ศูนย์', 'หนึ่ง', 'สอง', 'สาม', 'สี่', 'ห้า', 'หก', 'เจ็ด', 'แปด', 'เก้า']


def th_read(n):
    if n < 10: return WORDS[n]
    t, u = divmod(n, 10)
    if n == 100: return 'หนึ่งร้อย'
    s = ('สิบ' if t == 1 else ('ยี่สิบ' if t == 2 else WORDS[t] + 'สิบ'))
    return s + ('' if u == 0 else ('เอ็ด' if u == 1 else WORDS[u]))


def thai_num(n):
    return ''.join(TH_DIGIT[int(c)] for c in str(n))


def k_num(rng, mc):
    k = rng.randrange(4); n = R(rng, 1, 19)
    if k == 0: return NUM(f'เลขที่อยู่<b>ถัดจาก</b> {n} คือเลขอะไร', n + 1, ol(f'นับต่อจาก {n} หนึ่งตัว → {n+1}'))
    if k == 1: return NUM(f'เลขที่อยู่<b>ก่อน</b> {n + 1} คือเลขอะไร', n, ol(f'นับถอยหลังจาก {n+1} หนึ่งตัว → {n}'))
