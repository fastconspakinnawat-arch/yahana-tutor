def p_num100(rng, mc):
    k = rng.randrange(6); n = R(rng, 11, 99)
    if k == 0: return NUM(f'จำนวนที่อยู่ถัดจาก {n} คือจำนวนใด', n + 1, ol(f'{n} + 1 = {n+1}'))
    if k == 1:
        s = R(rng, 1, 7) * 10; st = rng.choice([2, 5, 10])
        seq = [s + st * i for i in range(4)]
        return NUM(f'นับเพิ่มทีละ {st}: {", ".join(map(str, seq))}, … จำนวนถัดไปคือ', s + st * 4, ol(f'เพิ่มทีละ {st} → {seq[-1]} + {st} = {s+st*4}'))
    if k == 2: return NUM(f'{n} มีเลขโดดในหลักสิบเป็นเท่าใด', n // 10, ol(f'{n} = {n//10} สิบ กับ {n%10} หน่วย', f'หลักสิบคือ {n//10}'))
    if k == 3: return NUM(f'{n // 10} สิบ กับ {n % 10} หน่วย คือจำนวนใด', n, ol(f'{n//10} × 10 + {n%10} = {n}'))
    if k == 4: return NUM(f'“{th_read(n)}” เขียนเป็นตัวเลขฮินดูอารบิกได้อย่างไร', n, ol(f'{th_read(n)} = {n}'))
    return mc(f'ตัวเลขไทย {thai_num(n)} คือจำนวนใด', str(n), [str(n + 10), str(int(str(n)[::-1])) if n % 10 else str(n + 1), str(n - 1), str(n + 1), str(n - 10)],
              ol(f'{thai_num(n)} = {n}'))


